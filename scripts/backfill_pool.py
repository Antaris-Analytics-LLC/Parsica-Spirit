def _promoted_labels(lb: dict) -> bool:
    """A record the promotion ledger is responsible for - same fields the planner's
    index keys on, plus the two the ledger key derivation needs."""
    return (lb.get("source") == PROMOTE_SOURCE and bool(lb.get("pk"))
            and lb.get("source_kind") in SOURCE_KINDS
            and bool(lb.get("source_record_id")))


def _rekeyed_candidate(new_scope: str, lb: dict, content: str) -> Optional[PromotionCandidate]:
    """The destination-ledger identity of a merged promoted record, derived through
    PromotionCandidate ITSELF so a future promote in NEW computes the same ledger key,
    pk, and content_hash by construction. Returns None (caller says so loudly) when
    the derivation disagrees with the record's own labels - a record this tool does
    not fully understand gets no ledger entry rather than a wrong one."""
    try:
        c = PromotionCandidate(scope_id=new_scope,
                               source_project=str(lb.get("source_project") or ""),
                               source_kind=str(lb["source_kind"]),
                               source_record_id=str(lb["source_record_id"]),
                               body=strip_provenance_tag(content))
    except (ValueError, KeyError):
        return None
    if c.provenance_key != lb.get("pk") or c.content_hash != lb.get("content_hash"):
        return None
    return c


def cmd_merge_scope(args) -> int:
    old = _scope_dirname(args.from_scope)
    new = _scope_dirname(args.into)
    if old == new:
        _say("--from and --into are the same scope (%s); nothing to merge" % old)
        return 2
    base = Path(args.spirit_root).expanduser()
    old_dir, new_dir = base / old, base / new
    marker = old_dir / (".merged-into-%s" % new)
    if marker.exists():
        _say("scope %s already merged into %s (%s exists) -- nothing to do; "
             "the old directory is yours to delete when satisfied" % (old, new, marker.name))
        return 0
    _require_store(old_dir, "nothing to merge")
    before = {p for p in old_dir.rglob("*") if p.is_file()}   # conservation baseline

    ctx_old = open_markdown(str(old_dir))
    old_records = _spirit_records(ctx_old, RouterScope(scope_id=old))
    old_records.sort(key=lambda r: r.id)                # deterministic manifest order
    old_ledger = SyncLedger(old_dir, old)               # constructor READS only
    ctx_new = open_markdown(str(new_dir))               # a write tool may scaffold NEW
    new_ids = {r.id for r in _spirit_records(ctx_new, RouterScope(scope_id=new))}
    new_ledger = SyncLedger(new_dir, new)

    _say("scope merge -- %s -> %s under %s" % (old, new, base))
    _say("records to re-home: %d" % len(old_records))
    counts = {"store": 0, "dup": 0, "retired": 0, "conflict": 0, "ledger": 0, "error": 0}
    total = len(old_records)
    for i, rec in enumerate(old_records, 1):
        lb = dict(rec.labels or {})
        promoted = _promoted_labels(lb)
        new_lkey = _ledger_key_for(new, lb) if promoted else ""
        if promoted and new_ledger.is_retired(new_lkey):
            counts["retired"] += 1
            _say("[%d/%d] SKIP    %s  source is RETIRED in the destination ledger -- "
                 "never resurrected; the live copy stays in the old dir" % (i, total, rec.id))
            continue
        if promoted and new_ledger.entry(new_lkey) is not None and rec.id not in new_ids:
            # the destination already tracks this SOURCE with different content -
            # storing a second body under the same pk would leave two live records
            # for one source (verify drift). The destination's version wins; the old
            # version stays readable in the left-in-place old dir.
            counts["conflict"] += 1
            _say("[%d/%d] SKIP    %s  destination ledger already tracks %s with "
                 "DIFFERENT content -- destination version kept; the old version "
                 "stays in the old dir" % (i, total, rec.id, new_lkey))
            continue
        labels = dict(lb)
        labels["scope_id"] = new                        # the scope relabel
        labels["merged_from"] = old
        target_id = rec.id
        try:
            if rec.id in new_ids:
                counts["dup"] += 1
                _say("[%d/%d] SKIP    %s  already in %s (content-identical) -- "
                     "destination copy kept untouched" % (i, total, rec.id, new))
            else:
                r = ctx_new.store(rec.content, labels=labels,
                                  enrich=rec.enrichment is not None)
                if not r.stored:
                    raise RuntimeError("store() persisted nothing")
                target_id = r.id
                counts["store"] += 1
                _say("[%d/%d] store   %s  -> scope %s (+merged_from=%s)"
                     % (i, total, rec.id, new, old))
                if r.id != rec.id:                      # should be impossible: scrub is idempotent
                    _say("[%d/%d] WARNING %s re-stored under a DIFFERENT id %s -- "
                         "inspect both copies" % (i, total, rec.id, r.id))
        except Exception as exc:                        # visible, never silent
            counts["error"] += 1
            _say("[%d/%d] ERROR   %s  %s: %s" % (i, total, rec.id,
                                                 type(exc).__name__, exc))
            continue
        if promoted:
            if new_ledger.entry(new_lkey) is not None:
                _say("[%d/%d] ledger  %s  destination already has this entry -- kept"
                     % (i, total, new_lkey))
            else:
                c = _rekeyed_candidate(new, lb, rec.content)
                if c is None:
                    _say("[%d/%d] WARNING %s  ledger identity does not re-derive from "
                         "the record's labels -- NO entry written; run promote --verify"
                         % (i, total, rec.id))
                else:
                    new_ledger.mark_active(c, target_id, action="merge")
                    counts["ledger"] += 1
                    _say("[%d/%d] ledger  %s  active -> spirit id %s"
                         % (i, total, new_lkey, target_id))

    # retirement intent lives ONLY in the ledger (no live record can testify for it),
    # so it is carried explicitly; a destination entry always wins a collision.
    old_prefix = "weave:%s:" % old
    old_entries = old_ledger.entries()
    for key in sorted(old_entries):
        e = old_entries[key]
        nkey = "weave:%s:%s" % (new, key[len(old_prefix):]) if key.startswith(old_prefix) else key
        if not key.startswith(old_prefix):
            _say("ledger  %s  key does not carry scope %s -- carried verbatim" % (key, old))
        if new_ledger.entry(nkey) is not None:
            continue                                    # covered above, or NEW's own history wins
        if e.get("state") == "retired":
            new_ledger.mark_retired(nkey, pk=str(e.get("pk") or ""))
            counts["ledger"] += 1
            _say("ledger  %s  retirement carried (no resurrection through %s)" % (nkey, new))
        else:
            _say("WARNING ledger %s is active in %s but has no live record -- NOT "
                 "carried; run promote --verify on the old scope" % (key, old))

    drift = verify_ledger(ctx_new, RouterScope(scope_id=new), new_ledger)
    for line in drift:
        _say("DRIFT: %s" % line)

    lost = sorted(str(p) for p in before if not p.exists())
    for p in lost:                                      # belt-and-suspenders: must be empty
        _say("CONSERVATION VIOLATION: %s existed before the merge and is gone" % p)

    summary = ["merged-into: %s" % new, "merged-from: %s" % old, "at: %s" % _utc_minute(),
               "stored: %d" % counts["store"], "duplicates-skipped: %d" % counts["dup"],
               "retired-skipped: %d" % counts["retired"],
               "conflicts-skipped: %d" % counts["conflict"],
               "ledger-entries: %d" % counts["ledger"], "errors: %d" % counts["error"],
               "note: this directory was left in place on purpose -- every byte is "
               "still yours; delete it yourself when satisfied"]
    if not counts["error"]:
        marker.write_text("\n".join(summary) + "\n", encoding="utf-8")
    _say("done: stored %(store)d | duplicates %(dup)d | retired %(retired)d "
         "| conflicts %(conflict)d | ledger %(ledger)d | errors %(error)d" % counts)
    _say("old scope dir left in place: %s%s" % (
        old_dir, "" if counts["error"] else " (marker %s written)" % marker.name))
    if counts["error"]:
        return 5
    if lost:
        return 5
    return 3 if drift else 0


# ---------------------------------------------------------------------------


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(
        prog="backfill_pool.py",
        description="Pool backfill + scope merge for the Spirit durable floor "
                    "(loud, idempotent, nothing unlinked ever).")
    sub = ap.add_subparsers(dest="cmd", required=True)

    b = sub.add_parser("backfill", help="backfill source_session/event_ts labels")
    b.add_argument("--spirit-root", required=True,
                   help="Spirit BASE dir (parent of per-scope stores)")
    b.add_argument("--scope", required=True, help="scope id (the store dir name)")
    b.add_argument("--weave-root", default="",
                   help="Weave STORE_ROOT for tier (a) mirror joins (optional)")
    b.set_defaults(fn=cmd_backfill)

    m = sub.add_parser("merge-scope", help="re-home every record from one scope into another")
    m.add_argument("--spirit-root", required=True,
                   help="Spirit BASE dir (parent of per-scope stores)")
    m.add_argument("--from", dest="from_scope", required=True, help="source scope id")
    m.add_argument("--into", required=True, help="destination scope id")
    m.set_defaults(fn=cmd_merge_scope)

    args = ap.parse_args(argv)
    try:
        return args.fn(args)
    except (ScopeRequired, IsolationViolation) as exc:
        _say("REFUSED (%s): %s" % (type(exc).__name__, exc))
        return 4


if __name__ == "__main__":
    sys.exit(main())
