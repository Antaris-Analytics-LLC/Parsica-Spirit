#!/usr/bin/env python3
"""Pool backfill + scope merge for the Parsica Spirit durable floor (migration tooling).

Two operator-invoked, loud, idempotent subcommands. Both print a FULL manifest - one
line per record - and neither ever unlinks anything: backfill is additive label writes
only, merge-scope leaves the source scope directory in place with a marker file (the
user deletes it when satisfied, never this tool).

  backfill --spirit-root R --scope S [--weave-root W]
      Give every record in scope S that is missing a `source_session` label its
      best-effort session provenance (the workspace contract: EVERY entry into the
      shared pool carries a session tag; retrieval treats an absent tag exactly like
      `pre-migration` - included, unattributed, never excluded - so this backfill is
      an enhancement pass, never a requirement). Three tiers:
        (a) source_record_id `enriched:<chunk_id>` + W given -> join the chunk id back
            to ANY project's capture mirror under the Weave store root W (active shards
            and rotation's archive/, both the workspace layout `mirror/<key>/` and the
            legacy `<key>/mirror/`) and backfill the REAL sess + the original event ts;
        (b) `journal:`/`lesson:` record ids -> the original event date is recoverable
            from the id itself; the session is unknowable -> `pre-migration`;
        (c) everything else -> `source_session: pre-migration`.
      Tier (b)'s event_ts is a bare `YYYY-MM-DD` (the honest resolution - the id
      carries no time of day). Additive-only: an already-present label value is NEVER
      overwritten, and records that already carry source_session are skipped, so a
      second run is a no-op.

  merge-scope --spirit-root R --from OLD --into NEW
      Re-home every record from scope OLD into scope NEW: read via the router gateway,
      store into NEW with ALL labels preserved plus the scope relabel and a
      `merged_from: OLD` label (the immediate previous scope; a longer chain stays
      readable in the left-in-place source dirs). Record ids are content-derived and
      the content is unchanged, so ids survive the move and content-hash dedup is an
      id check: a record already in NEW is skipped, loudly, untouched. Ledger
      continuity: active entries are re-derived through PromotionCandidate itself (the
      same class a future promote will use, so key/pk agreement is by construction)
      and re-keyed onto NEW's ledger; retired entries are carried so a retired source
      NEVER resurrects through a later promote; a destination entry always wins a
      collision. The enrichment overlay is regenerated by the destination Context for
      records that carried one (the overlay is retrieval-only and rebuildable; the
      seam accepts no foreign overlay). Finishes with verify_ledger on NEW and drops
      `.merged-into-<NEW>` in the OLD dir - the idempotency marker AND the audit
      breadcrumb. OLD's store files are never touched.

Every store write crosses the scrub-gated seam (ctx.store / ctx.relabel); every store
read crosses the router gateway (_spirit_records - fail-closed scope checks); the
ledger goes through SyncLedger's atomic writer. The ONLY direct file write is the
merge marker, a directory-level breadcrumb like migration's, never a store file.

--spirit-root is the Spirit BASE directory (the parent of per-scope stores, e.g.
~/.claude/parsica-spirit); the store for scope S lives at R/S - the same shape Weave's
promote/federation callers use. Exit codes: 0 ok (including nothing-to-do and the
already-merged short-circuit), 2 precondition (missing store / bad arguments),
3 verify_ledger drift after merge, 4 scope refusal / isolation violation, 5 write
errors (the manifest names each one).
"""

from __future__ import annotations

import argparse
import re
import sys
import time
from pathlib import Path
from typing import Dict, List, Optional, Tuple

from parsica_spirit import open_markdown
from parsica_spirit.promote import (
    PROMOTE_SOURCE, SOURCE_KINDS, PromotionCandidate, SyncLedger,
    _mirror_provenance, verify_ledger)
from parsica_spirit.router import (
    IsolationViolation, RouterScope, ScopeRequired, _spirit_records,
    strip_provenance_tag)

#: the sentinel session for records whose author is unknowable (pre-dating the
#: session-tag contract). Retrieval already treats an ABSENT tag identically, so the
#: sentinel adds nothing at read time - it exists so a backfilled store is visibly
#: DONE (every record answers the question) and a second pass has nothing to do.
PRE_MIGRATION = "pre-migration"

_DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
#: scope ids name store directories under --spirit-root; a path-shaped scope would
#: escape the base dir, so the charset is fenced before any filesystem touch.
_SCOPE_RE = re.compile(r"^[A-Za-z0-9._-]+$")
#: the promotion pk (provenance_key): a 16-hex digest. The ledger key derivation guards
#: on it so a malformed label yields no slot rather than a wrong one.
_PK_RE = re.compile(r"^[0-9a-f]{16}$")


def _ledger_key_for(scope: str, lb: dict) -> str:
    """The promotion ledger slot for a promoted record, in the provenance-keyed shape
    PromotionCandidate.ledger_key now produces (`weave:<scope>:<pk>`) - the pk folds
    source_project in, so two projects sharing a source_record_id no longer collide.
    Derived from the record's own `pk` label. Returns "" when that label is missing or
    is not the expected 16-hex, so a record this tool cannot key gets NO slot rather
    than a wrong one (consistent with _rekeyed_candidate's fail-closed re-derivation)."""
    pk = str(lb.get("pk") or "")
    if not _PK_RE.match(pk):
        return ""
    return "weave:%s:%s" % (scope, pk)


def _say(line: str) -> None:
    sys.stdout.write(line + "\n")


def _utc_minute() -> str:
    """Manifest/marker timestamp, promote's `created` spelling (store-time, UTC)."""
    return time.strftime("%Y-%m-%dT%H:%MZ", time.gmtime())


def _scope_dirname(scope: str) -> str:
    s = (scope or "").strip()
    if not s or s in (".", "..") or not _SCOPE_RE.match(s):
        raise SystemExit("scope %r is not a usable store directory name "
                         "(letters, digits, . _ - only)" % (scope,))
    return s


def _store_dir(spirit_root: str, scope: str) -> Path:
    return Path(spirit_root).expanduser() / _scope_dirname(scope)


def _require_store(store_dir: Path, what: str) -> None:
    """Refuse BEFORE open_markdown runs - opening scaffolds the root dir, and a
    migration tool pointed at a typo'd path must fail loudly, not mint an empty store."""
    if not (store_dir / "records.jsonl").exists():
        _say("no Spirit store at %s (records.jsonl absent) -- %s" % (store_dir, what))
        raise SystemExit(2)


def _weave_mirror_map(weave_root: Path) -> Dict[str, Tuple[str, str]]:
    """chunk id -> (sess, ts) across EVERY project's capture mirror under the Weave
    store root, both layouts: workspace (`mirror/<key>/` + per-project `archive/`) and
    legacy (`<key>/mirror/` + `archive/`). Read-only and provenance-only - promote's
    _mirror_provenance reads the two identity fields off each chunk and no text
    (raw chatter never promotes; it does not backfill either)."""
    dirs: List[Path] = []
    ws_mirror = weave_root / "mirror"
    if ws_mirror.is_dir():
        dirs += [d for d in sorted(ws_mirror.iterdir())
                 if d.is_dir() and d.name != "archive"]
    for d in sorted(weave_root.iterdir()):
        if d.is_dir() and (d / "mirror").is_dir():
            dirs.append(d / "mirror")
    out: Dict[str, Tuple[str, str]] = {}
    for d in dirs:
        out.update(_mirror_provenance(d))
    return out


# ---------------------------------------------------------------------------
# backfill
# ---------------------------------------------------------------------------

def cmd_backfill(args) -> int:
    scope = _scope_dirname(args.scope)
    store_dir = _store_dir(args.spirit_root, scope)
    _require_store(store_dir, "nothing to backfill")
    mirror: Optional[Dict[str, Tuple[str, str]]] = None
    if args.weave_root:
        wroot = Path(args.weave_root).expanduser()
        if not wroot.is_dir():
            # a typo'd weave root must not silently degrade every enriched record to
            # pre-migration - additive-only means a wrong sentinel is never overwritten
            # by a corrected re-run, so the mistake is refused up front instead.
            _say("weave root %s does not exist -- refusing (tier (a) would silently "
                 "degrade to pre-migration and additive-only writes never revise)" % wroot)
            return 2
        mirror = _weave_mirror_map(wroot)

    ctx = open_markdown(str(store_dir))
    records = _spirit_records(ctx, RouterScope(scope_id=scope))
    records.sort(key=lambda r: r.id)                    # deterministic manifest order
    _say("pool backfill -- scope %s at %s" % (scope, store_dir))
    _say("records: %d | mirror chunks joined: %s" % (
        len(records), len(mirror) if mirror is not None else "no --weave-root"))
    counts = {"a": 0, "b": 0, "c": 0, "skip": 0, "error": 0}
    total = len(records)
    for i, rec in enumerate(records, 1):
        lb = dict(rec.labels or {})
        if str(lb.get("source_session") or "").strip():
            counts["skip"] += 1
            _say("[%d/%d] skip    %s  source_session already set (%s)"
                 % (i, total, rec.id, lb["source_session"]))
            continue
        srid = str(lb.get("source_record_id") or "")
        add: Dict[str, str] = {}
        tier, note = "c", "no per-record provenance recoverable"
        if srid.startswith("enriched:"):
            cid = srid[len("enriched:"):]
            if mirror is None:
                note = "enriched turn but no --weave-root; session unknowable"
            else:
                sess, ts = mirror.get(cid, ("", ""))
                if sess or ts:
                    tier = "a"
                    add["source_session"] = sess or PRE_MIGRATION
                    note = ("session %s + event_ts %s from mirror chunk %s"
                            % (sess or "(blank -> %s)" % PRE_MIGRATION, ts or "(none)", cid))
                    if ts and not str(lb.get("event_ts") or "").strip():
                        add["event_ts"] = ts
                else:
                    note = "chunk %s not found in any mirror under the weave root" % cid
        elif srid.startswith("journal:") or srid.startswith("lesson:"):
            tier = "b"
            parts = srid.split(":")
            date = parts[1] if len(parts) > 1 else ""
            if _DATE_RE.match(date):
                note = "event date %s from the record id; session unknowable" % date
                if not str(lb.get("event_ts") or "").strip():
                    add["event_ts"] = date
            else:
                note = "event date unrecoverable (%r); session unknowable" % date
        add.setdefault("source_session", PRE_MIGRATION)
        try:
            if not ctx.relabel(rec.id, labels=add):
                raise RuntimeError("relabel returned False (record vanished?)")
        except Exception as exc:                        # visible, never silent
            counts["error"] += 1
            _say("[%d/%d] ERROR   %s  %s: %s" % (i, total, rec.id,
                                                 type(exc).__name__, exc))
            continue
        counts[tier] += 1
        _say("[%d/%d] tier=%s  %s  +%s  (%s)" % (
            i, total, tier, rec.id,
            " +".join("%s=%s" % (k, add[k]) for k in sorted(add)), note))
    _say("done: tier a %(a)d | tier b %(b)d | tier c %(c)d | skipped %(skip)d "
         "| errors %(error)d" % counts)
    return 5 if counts["error"] else 0


